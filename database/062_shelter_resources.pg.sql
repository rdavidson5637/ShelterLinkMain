-- Shelter resource library for volunteers (SL-DAY-04).
-- Staff add named links or uploaded handbook/policy files per shelter.
-- Volunteers read the active list; there is no public unauthenticated listing.
-- File bytes reuse object storage when configured, otherwise Postgres bytea.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS shelter_resources;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_resources();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS shelter_resources (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id     INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  title          VARCHAR(200) NOT NULL,
  kind           TEXT NOT NULL,
  url            TEXT DEFAULT NULL,
  filename       VARCHAR(255) DEFAULT NULL,
  original_name  VARCHAR(255) DEFAULT NULL,
  mime_type      VARCHAR(100) DEFAULT NULL,
  size           INTEGER DEFAULT NULL,
  content        BYTEA DEFAULT NULL,
  storage_key    TEXT DEFAULT NULL,
  sort_order     INTEGER NOT NULL DEFAULT 0,
  active         SMALLINT NOT NULL DEFAULT 1,
  created_by     INTEGER DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_resources_title_chk
    CHECK (char_length(btrim(title)) > 0),
  CONSTRAINT shelter_resources_kind_chk
    CHECK (kind IN ('link', 'file')),
  CONSTRAINT shelter_resources_active_chk
    CHECK (active IN (0, 1)),
  CONSTRAINT shelter_resources_link_chk
    CHECK (
      (kind = 'link' AND url IS NOT NULL AND char_length(btrim(url)) > 0
        AND content IS NULL AND storage_key IS NULL)
      OR (kind = 'file' AND url IS NULL
        AND (content IS NOT NULL OR storage_key IS NOT NULL))
    ),
  CONSTRAINT shelter_resources_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_resources_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_resources_shelter_sort_idx
  ON shelter_resources (shelter_id, active, sort_order, id);

CREATE UNIQUE INDEX IF NOT EXISTS uq_shelter_resources_storage_key
  ON shelter_resources (storage_key)
  WHERE storage_key IS NOT NULL;

ALTER TABLE shelter_resources ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_resources;
CREATE POLICY tenant_isolation ON shelter_resources
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_resources()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_resources;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_resources
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_resources();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_resources TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_resources_id_seq TO shelterlink_tenant;

COMMIT;
