-- Shelter closure dates (SL-LATER-30).
--   shelter_closures  per shelter. A closed day or an inclusive range of days
--                     (starts_on..ends_on, shelter-local dates) with a short
--                     reason such as "Christmas" or "Staff training".
-- App rules (controllers/closureController.js, utils/closureDates.js):
--   - Creating a shift, or generating a repeating series, whose start date
--     falls on a closed day is refused with a message naming the date.
--   - The public board and volunteer browse show "Closed" for those dates.
--   - Adding a closure lists shifts that already have bookings inside it.
--     Nothing is cancelled or emailed automatically; staff use the existing
--     close-shift path for each one.
-- Additive only: no existing table is altered. Existing shelters get no rows.
-- Safe to run more than once. Requires 033_add_shelters.pg.sql.
-- Feature branch only. The coordinator or keeper applies migrations in order
-- after a backup (npm run backup).
--
-- Rollback:
--   DROP TABLE IF EXISTS shelter_closures;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_shelter_closures();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS shelter_closures (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id  INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  starts_on   DATE NOT NULL,
  ends_on     DATE NOT NULL,
  reason      VARCHAR(120) NOT NULL,
  created_by  INTEGER,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_closures_range_chk CHECK (ends_on >= starts_on),
  CONSTRAINT shelter_closures_reason_chk CHECK (char_length(btrim(reason)) > 0),
  CONSTRAINT shelter_closures_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_closures_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_closures_shelter_dates_idx
  ON shelter_closures (shelter_id, ends_on, starts_on);

ALTER TABLE shelter_closures ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_closures;
CREATE POLICY tenant_isolation ON shelter_closures
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_shelter_closures()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_closures;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_closures
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_shelter_closures();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_closures TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_closures_id_seq TO shelterlink_tenant;

COMMIT;
