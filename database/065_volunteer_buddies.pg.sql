-- Buddy / mentor pairing for new volunteers (SL-DAY-08).
-- Staff assign an existing volunteer as a buddy. One active buddy per
-- volunteer. Optional email to the buddy on assign (staff click only).
-- Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS volunteer_buddies;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_volunteer_buddies();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS volunteer_buddies (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id          INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  volunteer_user_id   INTEGER NOT NULL,
  buddy_user_id       INTEGER NOT NULL,
  assigned_by         INTEGER DEFAULT NULL,
  assigned_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notify_emailed_at   TIMESTAMP DEFAULT NULL,
  CONSTRAINT volunteer_buddies_not_self_chk
    CHECK (volunteer_user_id <> buddy_user_id),
  CONSTRAINT volunteer_buddies_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_buddies_volunteer_user_id_fkey
    FOREIGN KEY (volunteer_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_buddies_buddy_user_id_fkey
    FOREIGN KEY (buddy_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_buddies_assigned_by_fkey
    FOREIGN KEY (assigned_by) REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT volunteer_buddies_volunteer_user_id_key UNIQUE (volunteer_user_id)
);

CREATE INDEX IF NOT EXISTS volunteer_buddies_shelter_buddy_idx
  ON volunteer_buddies (shelter_id, buddy_user_id);

CREATE INDEX IF NOT EXISTS volunteer_buddies_shelter_volunteer_idx
  ON volunteer_buddies (shelter_id, volunteer_user_id);

ALTER TABLE volunteer_buddies ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON volunteer_buddies;
CREATE POLICY tenant_isolation ON volunteer_buddies
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_volunteer_buddies()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.volunteer_user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.buddy_user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.assigned_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON volunteer_buddies;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON volunteer_buddies
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_volunteer_buddies();

GRANT SELECT, INSERT, UPDATE, DELETE ON volunteer_buddies TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE volunteer_buddies_id_seq TO shelterlink_tenant;

COMMIT;
