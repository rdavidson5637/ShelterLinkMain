-- ---------------------------------------------------------------------------
-- training_attempts
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_attempts (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id      INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  module_id       INTEGER NOT NULL,
  user_id         INTEGER NOT NULL,
  score_percent   SMALLINT NOT NULL,
  passed          SMALLINT NOT NULL DEFAULT 0,
  answers         JSONB NOT NULL,
  attempted_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT training_attempts_score_chk
    CHECK (score_percent >= 0 AND score_percent <= 100),
  CONSTRAINT training_attempts_passed_chk CHECK (passed IN (0, 1)),
  CONSTRAINT training_attempts_answers_chk CHECK (jsonb_typeof(answers) = 'array'),
  CONSTRAINT training_attempts_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT training_attempts_module_id_fkey
    FOREIGN KEY (module_id) REFERENCES training_modules (id) ON DELETE CASCADE,
  CONSTRAINT training_attempts_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS training_attempts_shelter_id_idx ON training_attempts (shelter_id);
CREATE INDEX IF NOT EXISTS training_attempts_module_user_idx
  ON training_attempts (module_id, user_id);
CREATE INDEX IF NOT EXISTS training_attempts_user_id_idx ON training_attempts (user_id);

ALTER TABLE training_attempts ENABLE ROW LEVEL SECURITY;
