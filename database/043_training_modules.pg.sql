-- Training modules with pass marks (SL-NEXT-04).
--   training_modules    per shelter. Reading content plus a pass_mark_percent.
--                       When a volunteer passes, awards_qualification_id is
--                       awarded through the existing volunteer_qualifications
--                       path so shift gates keep working.
--   training_questions  multiple-choice questions for a module. correct_index
--                       is 0-based into the choices JSON array. Volunteers
--                       never receive correct_index from the API.
--   training_attempts   each quiz submit. score_percent and passed are stored.
-- Safe to run more than once. Requires 033_add_shelters.pg.sql and
-- qualifications (010 / schema). Kept apart from 042 (booking policy) so the
-- branches do not collide on migration numbers.
-- Feature branch only. Do not apply to production until Ryan approves the
-- deploy and a backup exists (npm run backup).
--
-- Rollback:
--   DROP TABLE IF EXISTS training_attempts, training_questions, training_modules;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_training_attempts();
--   DROP FUNCTION IF EXISTS reject_cross_shelter_training_questions();
--   DROP FUNCTION IF EXISTS reject_cross_shelter_training_modules();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- training_modules
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_modules (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id                INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  name                      VARCHAR(255) NOT NULL,
  description               TEXT,
  content                   TEXT NOT NULL DEFAULT '',
  pass_mark_percent         SMALLINT NOT NULL DEFAULT 80,
  awards_qualification_id   INTEGER,
  active                    SMALLINT NOT NULL DEFAULT 1,
  created_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT training_modules_pass_mark_chk
    CHECK (pass_mark_percent >= 1 AND pass_mark_percent <= 100),
  CONSTRAINT training_modules_active_chk CHECK (active IN (0, 1)),
  CONSTRAINT training_modules_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT training_modules_awards_qualification_id_fkey
    FOREIGN KEY (awards_qualification_id) REFERENCES qualifications (id) ON DELETE SET NULL,
  CONSTRAINT training_modules_shelter_id_name_key UNIQUE (shelter_id, name)
);

CREATE INDEX IF NOT EXISTS training_modules_shelter_id_idx ON training_modules (shelter_id);
CREATE INDEX IF NOT EXISTS training_modules_awards_qualification_id_idx
  ON training_modules (awards_qualification_id);

ALTER TABLE training_modules ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON training_modules;
CREATE POLICY tenant_isolation ON training_modules
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_training_modules()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'qualifications', 'id', NEW.awards_qualification_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON training_modules;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON training_modules
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_training_modules();

DROP TRIGGER IF EXISTS trg_training_modules_updated_at ON training_modules;
CREATE TRIGGER trg_training_modules_updated_at
  BEFORE UPDATE ON training_modules
  FOR EACH ROW
  EXECUTE PROCEDURE set_updated_at();

-- ---------------------------------------------------------------------------
-- training_questions
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS training_questions (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id      INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  module_id       INTEGER NOT NULL,
  prompt          TEXT NOT NULL,
  choices         JSONB NOT NULL,
  correct_index   SMALLINT NOT NULL,
  sort_order      INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT training_questions_choices_chk CHECK (jsonb_typeof(choices) = 'array'),
  CONSTRAINT training_questions_correct_index_chk CHECK (correct_index >= 0),
  CONSTRAINT training_questions_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT training_questions_module_id_fkey
    FOREIGN KEY (module_id) REFERENCES training_modules (id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS training_questions_shelter_id_idx ON training_questions (shelter_id);
CREATE INDEX IF NOT EXISTS training_questions_module_id_idx ON training_questions (module_id);

