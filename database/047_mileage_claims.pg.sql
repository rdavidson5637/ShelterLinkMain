-- Mileage claims for volunteer travel (SL-LATER-07).
-- Volunteers submit miles for completed transport legs or other travel;
-- staff approve or reject. Miles only — no invented reimbursement rates.
-- Feature branch only. Do not apply to production until Ryan approves and a
-- backup exists (npm run backup).
--
-- Rollback:
--   DROP TABLE IF EXISTS mileage_claims;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_mileage_claims();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS mileage_claims (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id        INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  user_id           INTEGER NOT NULL,
  travel_date       DATE NOT NULL,
  miles             DECIMAL(8,2) NOT NULL,
  purpose           TEXT NOT NULL,
  transport_leg_id  INTEGER DEFAULT NULL,
  opportunity_id    INTEGER DEFAULT NULL,
  status            TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'approved', 'rejected')),
  reviewed_by       INTEGER DEFAULT NULL,
  reviewed_at       TIMESTAMP DEFAULT NULL,
  created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT mileage_claims_miles_chk CHECK (miles > 0 AND miles <= 2000),
  CONSTRAINT mileage_claims_purpose_chk CHECK (char_length(btrim(purpose)) > 0),
  CONSTRAINT mileage_claims_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT mileage_claims_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT mileage_claims_transport_leg_id_fkey
    FOREIGN KEY (transport_leg_id) REFERENCES transport_legs (id) ON DELETE SET NULL,
  CONSTRAINT mileage_claims_opportunity_id_fkey
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (opportunity_id) ON DELETE SET NULL,
  CONSTRAINT mileage_claims_reviewed_by_fkey
    FOREIGN KEY (reviewed_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS mileage_claims_shelter_id_idx ON mileage_claims (shelter_id);
CREATE INDEX IF NOT EXISTS mileage_claims_user_id_idx ON mileage_claims (user_id);
CREATE INDEX IF NOT EXISTS mileage_claims_status_idx ON mileage_claims (shelter_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS mileage_claims_transport_leg_unique
  ON mileage_claims (transport_leg_id)
  WHERE transport_leg_id IS NOT NULL;

ALTER TABLE mileage_claims ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON mileage_claims;
CREATE POLICY tenant_isolation ON mileage_claims
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_mileage_claims()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'transport_legs', 'id', NEW.transport_leg_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.reviewed_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON mileage_claims;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON mileage_claims
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_mileage_claims();

GRANT SELECT, INSERT, UPDATE, DELETE ON mileage_claims TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE mileage_claims_id_seq TO shelterlink_tenant;

COMMIT;
