-- Optional after-shift notes from volunteers (SL-DAY-11).
-- Short text only (no rating). Allowed after check-in (attended) or after the
-- shift end. Staff can read notes on the shift and volunteer pages. Optional
-- email to staff when the volunteer ticks notify and leaves a note.
-- Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS volunteer_shift_notes;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_volunteer_shift_notes();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS volunteer_shift_notes (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id       INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  application_id   INTEGER NOT NULL,
  user_id          INTEGER NOT NULL,
  opportunity_id   INTEGER NOT NULL,
  body             TEXT NOT NULL,
  notify           SMALLINT NOT NULL DEFAULT 0,
  notify_emailed_at TIMESTAMP DEFAULT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT volunteer_shift_notes_body_chk
    CHECK (char_length(btrim(body)) >= 1 AND char_length(body) <= 500),
  CONSTRAINT volunteer_shift_notes_notify_chk
    CHECK (notify IN (0, 1)),
  CONSTRAINT volunteer_shift_notes_application_id_key UNIQUE (application_id),
  CONSTRAINT volunteer_shift_notes_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_shift_notes_application_id_fkey
    FOREIGN KEY (application_id) REFERENCES applications (application_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_shift_notes_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_shift_notes_opportunity_id_fkey
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (opportunity_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS volunteer_shift_notes_shelter_user_idx
  ON volunteer_shift_notes (shelter_id, user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS volunteer_shift_notes_shelter_opportunity_idx
  ON volunteer_shift_notes (shelter_id, opportunity_id, created_at DESC);

ALTER TABLE volunteer_shift_notes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON volunteer_shift_notes;
CREATE POLICY tenant_isolation ON volunteer_shift_notes
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_volunteer_shift_notes()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.application_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON volunteer_shift_notes;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON volunteer_shift_notes
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_volunteer_shift_notes();

DROP TRIGGER IF EXISTS trg_volunteer_shift_notes_updated ON volunteer_shift_notes;
CREATE TRIGGER trg_volunteer_shift_notes_updated
  BEFORE UPDATE ON volunteer_shift_notes
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

GRANT SELECT, INSERT, UPDATE, DELETE ON volunteer_shift_notes TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE volunteer_shift_notes_id_seq TO shelterlink_tenant;

COMMIT;
