-- Platform audit log (self-serve brief section 9 item 5, section 4 criteria
-- 3, 9 and 12). Global table. One row per platform owner decision:
--   application.approved  an application became a live shelter
--   application.rejected  an application was turned down, with a reason
--   invite.created        a one-time admin invite was issued for a shelter
--   shelter.suspended     a shelter's status was set to suspended
-- Written only by routes/platform.js. Not visible to tenants. Shelter admins
-- keep their own audit_log; this table is separate so tenant code never
-- reads platform decisions.
-- The shelter column is named target_shelter_id, not shelter_id, because
-- this table is not tenant scoped and has no row level security.
-- Safe to run more than once. Requires 036_self_serve_shelters.pg.sql.
-- Do not run this against production until the deploy is approved.
--
-- Rollback:
--   DROP TABLE IF EXISTS platform_audit;

BEGIN;

CREATE TABLE IF NOT EXISTS platform_audit (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id      INTEGER,
  action             TEXT NOT NULL,
  application_id     INTEGER,
  target_shelter_id  INTEGER,
  detail             JSONB,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT platform_audit_action_chk CHECK (action IN ('application.approved','application.rejected','invite.created','shelter.suspended')),
  CONSTRAINT platform_audit_actor_user_id_fkey
    FOREIGN KEY (actor_user_id) REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT platform_audit_application_id_fkey
    FOREIGN KEY (application_id) REFERENCES shelter_applications (id) ON DELETE SET NULL,
  CONSTRAINT platform_audit_target_shelter_id_fkey
    FOREIGN KEY (target_shelter_id) REFERENCES shelters (id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS platform_audit_created_at_idx ON platform_audit (created_at);

-- 033 granted every table in public to shelterlink_tenant. On a fresh setup
-- that includes this one. Take it back: only platform routes use it.
REVOKE ALL ON platform_audit FROM shelterlink_tenant;
REVOKE ALL ON SEQUENCE platform_audit_id_seq FROM shelterlink_tenant;

COMMIT;
