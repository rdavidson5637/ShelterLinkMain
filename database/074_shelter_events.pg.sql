-- One-off shelter events (open days, fundraisers, clean-up days) (SL-DAY-20).
-- Separate from regular shifts. Staff create events with date, place, capacity
-- and description; volunteers sign up and cancel; staff see attendees and may
-- email them on an explicit click. Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS shelter_event_signups;
--   DROP TABLE IF EXISTS shelter_events;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_shelter_event_signups();
--   DROP FUNCTION IF EXISTS reject_cross_shelter_shelter_events();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS shelter_events (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id     INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  title          VARCHAR(160) NOT NULL,
  description    TEXT NOT NULL,
  event_date     DATE NOT NULL,
  location       VARCHAR(200) NOT NULL,
  capacity       INTEGER NOT NULL,
  archived_at    TIMESTAMP DEFAULT NULL,
  emailed_at     TIMESTAMP DEFAULT NULL,
  email_count    INTEGER NOT NULL DEFAULT 0,
  created_by     INTEGER DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_events_title_chk
    CHECK (char_length(btrim(title)) > 0),
  CONSTRAINT shelter_events_description_chk
    CHECK (char_length(btrim(description)) > 0),
  CONSTRAINT shelter_events_location_chk
    CHECK (char_length(btrim(location)) > 0),
  CONSTRAINT shelter_events_capacity_chk
    CHECK (capacity >= 1 AND capacity <= 9999),
  CONSTRAINT shelter_events_email_count_chk
    CHECK (email_count >= 0),
  CONSTRAINT shelter_events_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_events_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_events_shelter_active_idx
  ON shelter_events (shelter_id, archived_at, event_date ASC, id ASC);

CREATE INDEX IF NOT EXISTS shelter_events_shelter_date_idx
  ON shelter_events (shelter_id, event_date DESC, id DESC);

ALTER TABLE shelter_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_events;
CREATE POLICY tenant_isolation ON shelter_events
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_shelter_events()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_events;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_events
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_shelter_events();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_events TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_events_id_seq TO shelterlink_tenant;

CREATE TABLE IF NOT EXISTS shelter_event_signups (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id     INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  event_id       INTEGER NOT NULL,
  user_id        INTEGER NOT NULL,
  signed_up_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  cancelled_at   TIMESTAMP DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_event_signups_event_user_uq UNIQUE (event_id, user_id),
  CONSTRAINT shelter_event_signups_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_event_signups_event_id_fkey
    FOREIGN KEY (event_id) REFERENCES shelter_events (id) ON DELETE CASCADE,
  CONSTRAINT shelter_event_signups_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS shelter_event_signups_event_active_idx
  ON shelter_event_signups (shelter_id, event_id, cancelled_at);

CREATE INDEX IF NOT EXISTS shelter_event_signups_user_active_idx
  ON shelter_event_signups (shelter_id, user_id, cancelled_at);

ALTER TABLE shelter_event_signups ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_event_signups;
CREATE POLICY tenant_isolation ON shelter_event_signups
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_shelter_event_signups()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'shelter_events', 'id', NEW.event_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_event_signups;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_event_signups
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_shelter_event_signups();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_event_signups TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_event_signups_id_seq TO shelterlink_tenant;

COMMIT;
