-- Public supplies wishlist per shelter (SL-DAY-18).
-- Staff list items the shelter needs (name, quantity, priority, note).
-- Shown on the public shelter page with an "updated on" date.
-- No payments or donation processing. Email only elsewhere; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS shelter_wishlist_items;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_wishlist_items();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS shelter_wishlist_items (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id     INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  name           VARCHAR(160) NOT NULL,
  quantity       INTEGER NOT NULL DEFAULT 1,
  priority       TEXT NOT NULL DEFAULT 'medium',
  note           TEXT DEFAULT NULL,
  archived_at    TIMESTAMP DEFAULT NULL,
  created_by     INTEGER DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_wishlist_items_name_chk
    CHECK (char_length(btrim(name)) > 0),
  CONSTRAINT shelter_wishlist_items_quantity_chk
    CHECK (quantity >= 1 AND quantity <= 9999),
  CONSTRAINT shelter_wishlist_items_priority_chk
    CHECK (priority IN ('high', 'medium', 'low')),
  CONSTRAINT shelter_wishlist_items_note_chk
    CHECK (note IS NULL OR char_length(btrim(note)) > 0),
  CONSTRAINT shelter_wishlist_items_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_wishlist_items_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_wishlist_items_shelter_active_idx
  ON shelter_wishlist_items (shelter_id, archived_at, priority, id);

CREATE INDEX IF NOT EXISTS shelter_wishlist_items_shelter_updated_idx
  ON shelter_wishlist_items (shelter_id, updated_at DESC);

ALTER TABLE shelter_wishlist_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_wishlist_items;
CREATE POLICY tenant_isolation ON shelter_wishlist_items
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_wishlist_items()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_wishlist_items;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_wishlist_items
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_wishlist_items();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_wishlist_items TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_wishlist_items_id_seq TO shelterlink_tenant;

COMMIT;
