-- Usual days and parts of day a volunteer can help (SL-DAY-14).
-- Staff filling a short-staffed shift can list matching volunteers in the
-- same shelter and email one on an explicit click. Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS volunteer_usual_availability;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_volunteer_usual_availability();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS volunteer_usual_availability (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id    INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  user_id       INTEGER NOT NULL,
  weekday       TEXT NOT NULL,
  part_of_day   TEXT NOT NULL,
  updated_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT volunteer_usual_availability_weekday_chk
    CHECK (weekday IN ('mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun')),
  CONSTRAINT volunteer_usual_availability_part_chk
    CHECK (part_of_day IN ('morning', 'afternoon', 'evening')),
  CONSTRAINT volunteer_usual_availability_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_usual_availability_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_usual_availability_user_slot_key
    UNIQUE (user_id, weekday, part_of_day)
);

CREATE INDEX IF NOT EXISTS volunteer_usual_availability_shelter_slot_idx
  ON volunteer_usual_availability (shelter_id, weekday, part_of_day);

CREATE INDEX IF NOT EXISTS volunteer_usual_availability_shelter_user_idx
  ON volunteer_usual_availability (shelter_id, user_id);

ALTER TABLE volunteer_usual_availability ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON volunteer_usual_availability;
CREATE POLICY tenant_isolation ON volunteer_usual_availability
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_volunteer_usual_availability()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON volunteer_usual_availability;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON volunteer_usual_availability
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_volunteer_usual_availability();

DROP TRIGGER IF EXISTS trg_volunteer_usual_availability_updated_at ON volunteer_usual_availability;
CREATE TRIGGER trg_volunteer_usual_availability_updated_at
  BEFORE UPDATE ON volunteer_usual_availability
  FOR EACH ROW EXECUTE PROCEDURE set_updated_at();

GRANT SELECT, INSERT, UPDATE, DELETE ON volunteer_usual_availability TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE volunteer_usual_availability_id_seq TO shelterlink_tenant;

COMMIT;
