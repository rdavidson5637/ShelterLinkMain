-- Volunteer anniversary and shift milestones (SL-DAY-06).
-- Staff see a discreet notice when a volunteer reaches one year or 50
-- attended shifts, and can send a one-off thank-you email. Dedup rows stop
-- the same milestone being emailed twice. Email only; no SMS, no public
-- display, no scores.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS volunteer_milestone_emails;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_milestone_emails();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS volunteer_milestone_emails (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id      INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  user_id         INTEGER NOT NULL,
  milestone_kind  TEXT NOT NULL,
  emailed_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  emailed_by      INTEGER DEFAULT NULL,
  CONSTRAINT volunteer_milestone_emails_kind_chk
    CHECK (milestone_kind IN ('anniversary_1y', 'shifts_50')),
  CONSTRAINT volunteer_milestone_emails_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_milestone_emails_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_milestone_emails_emailed_by_fkey
    FOREIGN KEY (emailed_by) REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT volunteer_milestone_emails_user_kind_key UNIQUE (user_id, milestone_kind)
);

CREATE INDEX IF NOT EXISTS volunteer_milestone_emails_shelter_idx
  ON volunteer_milestone_emails (shelter_id, milestone_kind, emailed_at DESC);

ALTER TABLE volunteer_milestone_emails ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON volunteer_milestone_emails;
CREATE POLICY tenant_isolation ON volunteer_milestone_emails
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_milestone_emails()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.emailed_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON volunteer_milestone_emails;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON volunteer_milestone_emails
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_milestone_emails();

GRANT SELECT, INSERT, UPDATE, DELETE ON volunteer_milestone_emails TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE volunteer_milestone_emails_id_seq TO shelterlink_tenant;

COMMIT;
