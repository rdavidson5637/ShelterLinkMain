-- Under-18 rules (SL-NOW-02).
--   shelter_settings   per shelter. One row per shelter. min_volunteer_age is
--                      the shelter's own minimum age. NULL means the shelter
--                      has not set one, and no minimum is enforced. There is
--                      no global default age.
--   guardian_consents  per shelter. A parent or guardian's consent for a
--                      volunteer under 18. Withdrawing keeps the row and sets
--                      withdrawn_at, so the record of what was agreed stays.
-- Booking rule (enforced in the app, see utils/ageRules.js):
--   under the shelter minimum          -> cannot book
--   under 18 without active consent    -> cannot book
-- Existing shelters, including Assisi (id 1), get no row and so no minimum.
-- Safe to run more than once. Requires 033_add_shelters.pg.sql.
-- Feature branch only. Do not apply to production until Ryan approves the
-- deploy and a backup exists (npm run backup).
--
-- Rollback:
--   DROP TABLE IF EXISTS guardian_consents, shelter_settings;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_guardian_consents();
--   DROP FUNCTION IF EXISTS reject_cross_shelter_shelter_settings();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- shelter_settings
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS shelter_settings (
  shelter_id         INTEGER PRIMARY KEY DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  min_volunteer_age  SMALLINT,
  updated_by         INTEGER,
  updated_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_settings_min_age_chk CHECK (min_volunteer_age IS NULL OR (min_volunteer_age >= 1 AND min_volunteer_age <= 99)),
  CONSTRAINT shelter_settings_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_settings_updated_by_fkey
    FOREIGN KEY (updated_by) REFERENCES users (user_id) ON DELETE SET NULL
);

ALTER TABLE shelter_settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_settings;
CREATE POLICY tenant_isolation ON shelter_settings
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_shelter_settings()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.updated_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_settings;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_settings
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_shelter_settings();

-- ---------------------------------------------------------------------------
-- guardian_consents
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS guardian_consents (
  id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id             INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  user_id                INTEGER NOT NULL,
  guardian_name          VARCHAR(200) NOT NULL,
  guardian_relationship  VARCHAR(100) NOT NULL,
  guardian_phone         VARCHAR(40),
  guardian_email         VARCHAR(254),
  consented_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  recorded_by            INTEGER,
  withdrawn_at           TIMESTAMP,
  withdrawn_by           INTEGER,
  CONSTRAINT guardian_consents_contact_chk CHECK (guardian_phone IS NOT NULL OR guardian_email IS NOT NULL),
  CONSTRAINT guardian_consents_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT guardian_consents_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT guardian_consents_recorded_by_fkey
    FOREIGN KEY (recorded_by) REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT guardian_consents_withdrawn_by_fkey
    FOREIGN KEY (withdrawn_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS guardian_consents_shelter_id_idx ON guardian_consents (shelter_id);

-- At most one active consent per volunteer.
CREATE UNIQUE INDEX IF NOT EXISTS guardian_consents_active_key
  ON guardian_consents (shelter_id, user_id)
  WHERE withdrawn_at IS NULL;

ALTER TABLE guardian_consents ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON guardian_consents;
CREATE POLICY tenant_isolation ON guardian_consents
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_guardian_consents()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.recorded_by);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.withdrawn_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON guardian_consents;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON guardian_consents
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_guardian_consents();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_settings TO shelterlink_tenant;
GRANT SELECT, INSERT, UPDATE, DELETE ON guardian_consents TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE guardian_consents_id_seq TO shelterlink_tenant;

COMMIT;
