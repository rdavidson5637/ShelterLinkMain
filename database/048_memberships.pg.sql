-- Memberships: one login across sanctuaries (SL-LATER-08).
-- One row per (user, shelter) with that sanctuary's role. users.role and
-- users.shelter_id stay the source the app reads today; a trigger keeps the
-- primary membership row in sync. Adding a second sanctuary later inserts
-- another membership without a second account.
-- Feature branch only. Do not apply to production until Ryan approves and a
-- backup exists (npm run backup).
--
-- Rollback:
--   DROP TRIGGER IF EXISTS trg_sync_user_membership ON users;
--   DROP FUNCTION IF EXISTS sync_user_membership();
--   DROP TABLE IF EXISTS memberships;

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS memberships (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     INTEGER NOT NULL,
  shelter_id  INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  role        TEXT NOT NULL DEFAULT 'volunteer'
              CHECK (role IN ('volunteer', 'staff', 'admin')),
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT memberships_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT memberships_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT memberships_user_shelter_key UNIQUE (user_id, shelter_id)
);

CREATE INDEX IF NOT EXISTS memberships_shelter_id_idx ON memberships (shelter_id);
CREATE INDEX IF NOT EXISTS memberships_user_id_idx ON memberships (user_id);
CREATE INDEX IF NOT EXISTS memberships_shelter_role_idx ON memberships (shelter_id, role);

ALTER TABLE memberships ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON memberships;
CREATE POLICY tenant_isolation ON memberships
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

-- No same-shelter trigger against users.shelter_id: a person may hold
-- memberships at more than one sanctuary while users.shelter_id is only the
-- current primary. The FK to users is enough.

-- Backfill one membership from each existing user that already has a shelter.
INSERT INTO memberships (user_id, shelter_id, role, created_at, updated_at)
SELECT u.user_id, u.shelter_id, u.role, u.created_at, CURRENT_TIMESTAMP
FROM users u
WHERE u.shelter_id IS NOT NULL
ON CONFLICT (user_id, shelter_id) DO UPDATE
  SET role = EXCLUDED.role,
      updated_at = CURRENT_TIMESTAMP;

-- Keep the primary membership aligned with users.role / users.shelter_id.
CREATE OR REPLACE FUNCTION sync_user_membership()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF NEW.shelter_id IS NULL THEN
    RETURN NEW;
  END IF;
  INSERT INTO memberships (user_id, shelter_id, role)
  VALUES (NEW.user_id, NEW.shelter_id, NEW.role)
  ON CONFLICT (user_id, shelter_id) DO UPDATE
    SET role = EXCLUDED.role,
        updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sync_user_membership ON users;
CREATE TRIGGER trg_sync_user_membership
  AFTER INSERT OR UPDATE OF shelter_id, role ON users
  FOR EACH ROW EXECUTE FUNCTION sync_user_membership();

COMMIT;
