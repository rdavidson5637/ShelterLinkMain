-- Shelter announcements for volunteers (SL-DAY-17).
-- Staff post short dated notices shown on the volunteer home for that shelter.
-- Optional email to active (approved) volunteers only on an explicit staff click.
-- Expiry date and archive. Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS shelter_announcements;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_shelter_announcements();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS shelter_announcements (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id     INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  title          VARCHAR(160) NOT NULL,
  body           TEXT NOT NULL,
  posted_on      DATE NOT NULL DEFAULT (CURRENT_DATE),
  expires_on     DATE DEFAULT NULL,
  archived_at    TIMESTAMP DEFAULT NULL,
  emailed_at     TIMESTAMP DEFAULT NULL,
  email_count    INTEGER NOT NULL DEFAULT 0,
  created_by     INTEGER DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_announcements_title_chk
    CHECK (char_length(btrim(title)) > 0),
  CONSTRAINT shelter_announcements_body_chk
    CHECK (char_length(btrim(body)) > 0),
  CONSTRAINT shelter_announcements_expires_chk
    CHECK (expires_on IS NULL OR expires_on >= posted_on),
  CONSTRAINT shelter_announcements_email_count_chk
    CHECK (email_count >= 0),
  CONSTRAINT shelter_announcements_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT shelter_announcements_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_announcements_shelter_active_idx
  ON shelter_announcements (shelter_id, archived_at, expires_on, posted_on DESC, id DESC);

CREATE INDEX IF NOT EXISTS shelter_announcements_shelter_posted_idx
  ON shelter_announcements (shelter_id, posted_on DESC, id DESC);

ALTER TABLE shelter_announcements ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON shelter_announcements;
CREATE POLICY tenant_isolation ON shelter_announcements
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_shelter_announcements()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON shelter_announcements;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON shelter_announcements
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_shelter_announcements();

GRANT SELECT, INSERT, UPDATE, DELETE ON shelter_announcements TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE shelter_announcements_id_seq TO shelterlink_tenant;

COMMIT;
