-- Private staff notes on a volunteer profile (SL-DAY-15).
-- Staff-only. Tenant-scoped via RLS. Author and time shown in the UI.
-- Edits are audit-logged via the admin mutation middleware.
-- Never exposed on volunteer surfaces or in GDPR / self-export payloads.
-- Email only; no SMS.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS volunteer_staff_notes;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_volunteer_staff_notes();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS volunteer_staff_notes (
  id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id          INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  volunteer_user_id   INTEGER NOT NULL,
  author_user_id      INTEGER NOT NULL,
  body                TEXT NOT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by          INTEGER DEFAULT NULL,
  CONSTRAINT volunteer_staff_notes_body_not_blank_chk
    CHECK (length(btrim(body)) > 0),
  CONSTRAINT volunteer_staff_notes_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_staff_notes_volunteer_user_id_fkey
    FOREIGN KEY (volunteer_user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT volunteer_staff_notes_author_user_id_fkey
    FOREIGN KEY (author_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
  CONSTRAINT volunteer_staff_notes_updated_by_fkey
    FOREIGN KEY (updated_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS volunteer_staff_notes_shelter_volunteer_idx
  ON volunteer_staff_notes (shelter_id, volunteer_user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS volunteer_staff_notes_shelter_created_idx
  ON volunteer_staff_notes (shelter_id, created_at DESC);

ALTER TABLE volunteer_staff_notes ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON volunteer_staff_notes;
CREATE POLICY tenant_isolation ON volunteer_staff_notes
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_volunteer_staff_notes()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.volunteer_user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.author_user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.updated_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON volunteer_staff_notes;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON volunteer_staff_notes
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_volunteer_staff_notes();

GRANT SELECT, INSERT, UPDATE, DELETE ON volunteer_staff_notes TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE volunteer_staff_notes_id_seq TO shelterlink_tenant;

COMMIT;
