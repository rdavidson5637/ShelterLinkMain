-- ----------------------------------------------------------------------------
-- shelters
-- Same definition as database/033_add_shelters.pg.sql (see
-- docs/tenancy/design.md). 033 still runs after this file: it inserts Assisi
-- as id 1, adds shelter_id to every tenant table, and enables row level
-- security. Keep the two definitions in step. The charity, status, privacy
-- and colour columns come from database/036_self_serve_shelters.pg.sql.
-- ----------------------------------------------------------------------------
CREATE TABLE shelters (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(255) NOT NULL,
  slug        VARCHAR(100) NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  logo        BYTEA,
  logo_mime   VARCHAR(100),
  logo_storage_key TEXT DEFAULT NULL,
  charity_regulator TEXT CONSTRAINT shelters_charity_regulator_chk CHECK (charity_regulator IN ('ccew','oscr','ccni','cri')),
  charity_number VARCHAR(32),
  charity_register_name VARCHAR(255),
  charity_checked_at TIMESTAMP,
  status TEXT NOT NULL DEFAULT 'active' CONSTRAINT shelters_status_chk CHECK (status IN ('active','suspended')),
  privacy_contact_email VARCHAR(255),
  primary_colour VARCHAR(7) CONSTRAINT shelters_primary_colour_chk CHECK (primary_colour ~ '^#[0-9A-Fa-f]{6}$'),
  setup_checklist_dismissed_at TIMESTAMP NULL,
  CONSTRAINT shelters_slug_key UNIQUE (slug),
  CONSTRAINT shelters_slug_lowercase_chk CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  CONSTRAINT shelters_charity_pair_chk CHECK ((charity_regulator IS NULL) = (charity_number IS NULL))
);

CREATE UNIQUE INDEX shelters_charity_key
  ON shelters (charity_regulator, charity_number)
  WHERE charity_regulator IS NOT NULL AND charity_number IS NOT NULL;

CREATE UNIQUE INDEX uq_shelters_logo_storage_key
  ON shelters (logo_storage_key)
  WHERE logo_storage_key IS NOT NULL;

