-- A tenant insert carries the caller's shelter_id. Foreign keys are on the
-- parent id only, so reject a reference whose parent row belongs to another
-- shelter. The same error is raised when the parent is missing, so this
-- cannot be used to tell those two cases apart.
CREATE OR REPLACE FUNCTION assert_same_shelter(expected integer, tbl text, col text, val integer)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  sid integer;
BEGIN
  IF val IS NULL THEN
    RETURN;
  END IF;
  EXECUTE format('SELECT shelter_id FROM %I WHERE %I = $1', tbl, col) INTO sid USING val;
  IF sid IS NULL OR sid IS DISTINCT FROM expected THEN
    RAISE EXCEPTION 'cross-tenant reference' USING ERRCODE = 'P0001';
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION assert_same_shelter(integer, text, text, integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION assert_same_shelter(integer, text, text, integer) TO shelterlink_tenant;

CREATE OR REPLACE FUNCTION reject_cross_shelter()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  IF TG_TABLE_NAME = 'volunteer_profiles' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'opportunities' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.parent_opportunity_id);
  ELSIF TG_TABLE_NAME = 'applications' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  ELSIF TG_TABLE_NAME = 'shift_feedback' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.application_id);
  ELSIF TG_TABLE_NAME = 'swap_requests' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.application_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.claimed_by_application_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.waitlist_offered_to_user_id);
  ELSIF TG_TABLE_NAME = 'volunteer_hours' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  ELSIF TG_TABLE_NAME = 'volunteer_qualifications' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'qualifications', 'id', NEW.qualification_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.awarded_by);
  ELSIF TG_TABLE_NAME = 'opportunity_qualifications' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'qualifications', 'id', NEW.qualification_id);
  ELSIF TG_TABLE_NAME = 'volunteer_tags' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'tags', 'id', NEW.tag_id);
  ELSIF TG_TABLE_NAME = 'opportunity_tags' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'tags', 'id', NEW.tag_id);
  ELSIF TG_TABLE_NAME = 'opportunity_match_queue' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'tag_digest_log' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'custom_field_values' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'custom_fields', 'id', NEW.field_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'waiver_acceptances' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'waivers', 'id', NEW.waiver_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'user_documents' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'admin_messages' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.admin_id);
  ELSIF TG_TABLE_NAME = 'audit_log' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'group_bookings' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  ELSIF TG_TABLE_NAME = 'animals' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'qualifications', 'id', NEW.requires_qualification_id);
  ELSIF TG_TABLE_NAME = 'opportunity_animals' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
  ELSIF TG_TABLE_NAME = 'animal_activity' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.application_id);
  ELSIF TG_TABLE_NAME = 'animal_photos' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
  ELSIF TG_TABLE_NAME = 'foster_requests' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  ELSIF TG_TABLE_NAME = 'foster_offers' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'foster_requests', 'id', NEW.request_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'foster_placements' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'foster_requests', 'id', NEW.request_id);
  ELSIF TG_TABLE_NAME = 'transport_runs' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  ELSIF TG_TABLE_NAME = 'transport_legs' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'transport_runs', 'id', NEW.run_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.claimed_by);
  ELSIF TG_TABLE_NAME = 'incidents' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'animals', 'id', NEW.animal_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.reported_by);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.resolved_by);
  ELSIF TG_TABLE_NAME = 'message_threads' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  ELSIF TG_TABLE_NAME = 'thread_participants' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'message_threads', 'id', NEW.thread_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'messages' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'message_threads', 'id', NEW.thread_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.deleted_by);
  ELSIF TG_TABLE_NAME = 'message_digest_log' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'shift_notes' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.author_id);
  ELSIF TG_TABLE_NAME = 'certificates' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'volunteer_references' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'background_checks' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.updated_by);
  ELSIF TG_TABLE_NAME = 'push_subscriptions' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  ELSIF TG_TABLE_NAME = 'opportunity_templates' THEN
    PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  END IF;
  RETURN NEW;
END;
$$;

