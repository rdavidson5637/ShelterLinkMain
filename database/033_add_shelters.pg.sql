-- Shelter tenancy for this Postgres app.
-- Adds public.shelters and shelter_id on every per-shelter table, then enables
-- row level security for role shelterlink_tenant.
-- The app SET LOCAL ROLE shelterlink_tenant and sets app.shelter_id from the
-- logged-in user. The postgres role used by this app bypasses RLS unless that
-- role switch happens.
-- session, job_runs, and schema_migrations stay global.
-- Do not apply this file to the live ShelterLinkMain database until deploy is approved.

CREATE ROLE shelterlink_tenant NOLOGIN NOBYPASSRLS;
GRANT shelterlink_tenant TO CURRENT_USER;
GRANT shelterlink_tenant TO postgres;
ALTER ROLE shelterlink_tenant SET search_path TO public;

