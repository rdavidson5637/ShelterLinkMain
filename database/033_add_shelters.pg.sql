    EXECUTE format('DROP TRIGGER IF EXISTS trg_same_shelter ON %I', t);
    EXECUTE format(
      'CREATE TRIGGER trg_same_shelter BEFORE INSERT OR UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter()',
      t
    );
  END LOOP;
END $$;

