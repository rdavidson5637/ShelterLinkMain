-- New-volunteer induction checklist (SL-DAY-02).
-- Staff define a small per-shelter checklist (welcome email, site tour,
-- shadow shift, policies acknowledged, etc.). Each volunteer has progress
-- against those items; staff tick items on the volunteer profile.
--
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS induction_checklist_progress, induction_checklist_items;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_induction_progress();
--   DROP FUNCTION IF EXISTS reject_cross_shelter_induction_items();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- induction_checklist_items — shelter default checklist template
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS induction_checklist_items (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id  INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  title       VARCHAR(200) NOT NULL,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  active      SMALLINT NOT NULL DEFAULT 1,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT induction_checklist_items_title_chk
    CHECK (char_length(btrim(title)) > 0),
  CONSTRAINT induction_checklist_items_active_chk CHECK (active IN (0, 1)),
  CONSTRAINT induction_checklist_items_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS induction_checklist_items_shelter_sort_idx
  ON induction_checklist_items (shelter_id, active, sort_order, id);

ALTER TABLE induction_checklist_items ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON induction_checklist_items;
CREATE POLICY tenant_isolation ON induction_checklist_items
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_induction_items()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON induction_checklist_items;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON induction_checklist_items
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_induction_items();

GRANT SELECT, INSERT, UPDATE, DELETE ON induction_checklist_items TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE induction_checklist_items_id_seq TO shelterlink_tenant;

-- ---------------------------------------------------------------------------
-- induction_checklist_progress — per-volunteer ticks
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS induction_checklist_progress (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id    INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  user_id       INTEGER NOT NULL,
  item_id       INTEGER NOT NULL,
  completed_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_by  INTEGER DEFAULT NULL,
  CONSTRAINT induction_checklist_progress_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT induction_checklist_progress_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT induction_checklist_progress_item_id_fkey
    FOREIGN KEY (item_id) REFERENCES induction_checklist_items (id) ON DELETE CASCADE,
  CONSTRAINT induction_checklist_progress_completed_by_fkey
    FOREIGN KEY (completed_by) REFERENCES users (user_id) ON DELETE SET NULL,
  CONSTRAINT induction_checklist_progress_user_item_key UNIQUE (user_id, item_id)
);

CREATE INDEX IF NOT EXISTS induction_checklist_progress_shelter_user_idx
  ON induction_checklist_progress (shelter_id, user_id);
CREATE INDEX IF NOT EXISTS induction_checklist_progress_item_idx
  ON induction_checklist_progress (item_id);

ALTER TABLE induction_checklist_progress ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON induction_checklist_progress;
CREATE POLICY tenant_isolation ON induction_checklist_progress
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_induction_progress()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'induction_checklist_items', 'id', NEW.item_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.completed_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON induction_checklist_progress;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON induction_checklist_progress
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_induction_progress();

GRANT SELECT, INSERT, UPDATE, DELETE ON induction_checklist_progress TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE induction_checklist_progress_id_seq TO shelterlink_tenant;

COMMIT;
