-- Self-serve shelter onboarding: data model only (brief section 5).
-- Adds charity register and status columns to shelters, plus three tables:
--   shelter_applications  global. A charity asks to join. A platform owner
--                         approves or rejects it. Not visible to tenants.
--   admin_invites         per shelter. One-time admin or staff invite links.
--   platform_owners       global. Users who may approve new shelters.
-- No routes use these yet. Existing shelters, including Assisi (id 1), keep
-- working: every new shelters column is nullable or defaults to 'active'.
-- Safe to run more than once. Requires 033_add_shelters.pg.sql.
-- Take a backup first (npm run backup). Do not run this against production
-- until that backup exists and the deploy is approved.
--
-- Rollback:
--   DROP TABLE IF EXISTS admin_invites, shelter_applications, platform_owners;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_admin_invites();
--   DROP INDEX IF EXISTS shelters_charity_key;
--   ALTER TABLE shelters DROP CONSTRAINT IF EXISTS shelters_charity_pair_chk;
--   ALTER TABLE shelters
--     DROP COLUMN IF EXISTS charity_regulator,
--     DROP COLUMN IF EXISTS charity_number,
--     DROP COLUMN IF EXISTS charity_register_name,
--     DROP COLUMN IF EXISTS charity_checked_at,
--     DROP COLUMN IF EXISTS status,
--     DROP COLUMN IF EXISTS privacy_contact_email,
--     DROP COLUMN IF EXISTS primary_colour;

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- shelters: charity register details, status, privacy contact, brand colour
-- ---------------------------------------------------------------------------
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS charity_regulator TEXT CONSTRAINT shelters_charity_regulator_chk CHECK (charity_regulator IN ('ccew','oscr','ccni','cri'));
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS charity_number VARCHAR(32);
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS charity_register_name VARCHAR(255);
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS charity_checked_at TIMESTAMP;
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'active' CONSTRAINT shelters_status_chk CHECK (status IN ('active','suspended'));
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS privacy_contact_email VARCHAR(255);
ALTER TABLE shelters ADD COLUMN IF NOT EXISTS primary_colour VARCHAR(7) CONSTRAINT shelters_primary_colour_chk CHECK (primary_colour ~ '^#[0-9A-Fa-f]{6}$');

-- Regulator and number are set together or not at all.
ALTER TABLE shelters DROP CONSTRAINT IF EXISTS shelters_charity_pair_chk;
ALTER TABLE shelters ADD CONSTRAINT shelters_charity_pair_chk CHECK ((charity_regulator IS NULL) = (charity_number IS NULL));

-- One shelter per registered charity.
CREATE UNIQUE INDEX IF NOT EXISTS shelters_charity_key
  ON shelters (charity_regulator, charity_number)
  WHERE charity_regulator IS NOT NULL AND charity_number IS NOT NULL;

-- Existing rows, including Assisi, take status 'active' from the column
-- default when the column is added. The charity columns stay NULL.

-- ---------------------------------------------------------------------------
-- shelter_applications (global, platform owners only)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS shelter_applications (
  id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_name       VARCHAR(255) NOT NULL,
  desired_slug       VARCHAR(100) NOT NULL,
  regulator          TEXT NOT NULL,
  charity_number     VARCHAR(32) NOT NULL,
  register_snapshot  JSONB,
  contact_name       VARCHAR(200) NOT NULL,
  contact_email      VARCHAR(255) NOT NULL,
  status             TEXT NOT NULL DEFAULT 'pending',
  decided_by         INTEGER,
  decided_at         TIMESTAMP,
  reason             TEXT,
  created_at         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT shelter_applications_slug_chk CHECK (desired_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  CONSTRAINT shelter_applications_regulator_chk CHECK (regulator IN ('ccew','oscr','ccni','cri')),
  CONSTRAINT shelter_applications_status_chk CHECK (status IN ('pending','approved','rejected')),
  CONSTRAINT shelter_applications_decided_chk CHECK ((status = 'pending') = (decided_at IS NULL)),
  CONSTRAINT shelter_applications_decided_by_fkey
    FOREIGN KEY (decided_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS shelter_applications_status_idx
  ON shelter_applications (status, created_at);

-- ---------------------------------------------------------------------------
-- platform_owners (global). Separate from users.role on purpose: a platform
-- owner is not a shelter admin, and tenant queries must never grant it.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS platform_owners (
  user_id     INTEGER PRIMARY KEY,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT platform_owners_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- admin_invites (per shelter, same RLS pattern as 033)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admin_invites (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id  INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  email       VARCHAR(255) NOT NULL,
  token_hash  VARCHAR(128) NOT NULL,
  role        TEXT NOT NULL,
  expires_at  TIMESTAMP NOT NULL,
  used_at     TIMESTAMP,
  created_by  INTEGER,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT admin_invites_token_hash_key UNIQUE (token_hash),
  CONSTRAINT admin_invites_role_chk CHECK (role IN ('admin','staff')),
  CONSTRAINT admin_invites_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT admin_invites_created_by_fkey
    FOREIGN KEY (created_by) REFERENCES users (user_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS admin_invites_shelter_id_idx ON admin_invites (shelter_id);

ALTER TABLE admin_invites ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON admin_invites;
CREATE POLICY tenant_isolation ON admin_invites
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

-- created_by must be a user in the same shelter (see assert_same_shelter in 033).
CREATE OR REPLACE FUNCTION reject_cross_shelter_admin_invites()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.created_by);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON admin_invites;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON admin_invites
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_admin_invites();

-- ---------------------------------------------------------------------------
-- Grants. 033 granted every existing table to shelterlink_tenant, which on a
-- fresh install includes the two global tables above. Take that back.
-- ---------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON admin_invites TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE admin_invites_id_seq TO shelterlink_tenant;
REVOKE ALL ON shelter_applications FROM shelterlink_tenant;
REVOKE ALL ON SEQUENCE shelter_applications_id_seq FROM shelterlink_tenant;
REVOKE ALL ON platform_owners FROM shelterlink_tenant;

COMMIT;
