-- Timed waitlist seat offers (SL-LATER-23).
-- When a place frees on a full shift, the first eligible waitlisted volunteer
-- gets a time-limited claim link (email + push). If they do not claim, the
-- next eligible person is offered. Quiet hours delay notify; job_runs dedupes.
-- Feature branch only. Do not apply to production until the coordinator or
-- keeper runs migrations in order after a backup.
--
-- Rollback:
--   DROP TABLE IF EXISTS waitlist_offers;
--   DROP FUNCTION IF EXISTS reject_cross_shelter_waitlist_offers();

BEGIN;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM shelters WHERE id = 1 AND slug = 'assisi') THEN
    RAISE EXCEPTION 'Shelter id 1 slug assisi is missing. Apply 033 first.';
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS waitlist_offers (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shelter_id       INTEGER NOT NULL DEFAULT (NULLIF(current_setting('app.shelter_id', true), '')::integer),
  opportunity_id   INTEGER NOT NULL,
  application_id   INTEGER NOT NULL,
  user_id          INTEGER NOT NULL,
  claim_token      VARCHAR(64) NOT NULL,
  status           TEXT NOT NULL DEFAULT 'offered'
                   CHECK (status IN ('offered', 'claimed', 'expired', 'cancelled')),
  offered_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  notified_at      TIMESTAMP DEFAULT NULL,
  expires_at       TIMESTAMP DEFAULT NULL,
  claimed_at       TIMESTAMP DEFAULT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT waitlist_offers_shelter_id_fkey
    FOREIGN KEY (shelter_id) REFERENCES shelters (id) ON DELETE RESTRICT,
  CONSTRAINT waitlist_offers_opportunity_id_fkey
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (opportunity_id) ON DELETE CASCADE,
  CONSTRAINT waitlist_offers_application_id_fkey
    FOREIGN KEY (application_id) REFERENCES applications (application_id) ON DELETE CASCADE,
  CONSTRAINT waitlist_offers_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
  CONSTRAINT waitlist_offers_claim_token_key UNIQUE (claim_token)
);

CREATE INDEX IF NOT EXISTS waitlist_offers_shelter_id_idx ON waitlist_offers (shelter_id);
CREATE INDEX IF NOT EXISTS waitlist_offers_opportunity_status_idx
  ON waitlist_offers (opportunity_id, status);
CREATE INDEX IF NOT EXISTS waitlist_offers_expires_idx
  ON waitlist_offers (status, expires_at)
  WHERE status = 'offered';
CREATE UNIQUE INDEX IF NOT EXISTS waitlist_offers_one_active_per_opportunity
  ON waitlist_offers (opportunity_id)
  WHERE status = 'offered';

ALTER TABLE waitlist_offers ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON waitlist_offers;
CREATE POLICY tenant_isolation ON waitlist_offers
  FOR ALL
  TO shelterlink_tenant
  USING (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer)
  WITH CHECK (shelter_id = NULLIF(current_setting('app.shelter_id', true), '')::integer);

CREATE OR REPLACE FUNCTION reject_cross_shelter_waitlist_offers()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  PERFORM assert_same_shelter(NEW.shelter_id, 'opportunities', 'opportunity_id', NEW.opportunity_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'applications', 'application_id', NEW.application_id);
  PERFORM assert_same_shelter(NEW.shelter_id, 'users', 'user_id', NEW.user_id);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_same_shelter ON waitlist_offers;
CREATE TRIGGER trg_same_shelter
  BEFORE INSERT OR UPDATE ON waitlist_offers
  FOR EACH ROW EXECUTE FUNCTION reject_cross_shelter_waitlist_offers();

GRANT SELECT, INSERT, UPDATE, DELETE ON waitlist_offers TO shelterlink_tenant;
GRANT USAGE, SELECT ON SEQUENCE waitlist_offers_id_seq TO shelterlink_tenant;

COMMIT;
